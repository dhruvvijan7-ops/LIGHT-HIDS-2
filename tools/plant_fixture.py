#!/usr/bin/env python3
"""Derive the M2 planted-finding EVTX from the pinned evtx-rs sample.

M2 exit ① needs a committed EVTX that contains a *known-bad* process creation
which a pinned SigmaHQ rule must match (spec §6.3).  The source capture itself
is never committed (D6-009 / §6.2 - raw captures stay out of the tree), so
the drill works from a derived fixture:

  1. take record 1742 of ``evtx-rs/samples/sysmon.evtx`` (a Sysmon EID 1
     process creation whose command line is a plain ``ping``),
  2. overwrite that one UTF-16LE substitution value in place with a
     same-length command line (``ping.exe whoami /priv``) that matches
     ``proc_creation_win_susp_whoami_as_param``,
  3. keep only the file header and the first 64 KiB chunk, which is where the
     record lives - the sample's tail chunks are truncated upstream and make
     the parser report ``Failed to parse chunk header``.

Equal-length, in-place replacement keeps every record size, template
descriptor and offset in the chunk untouched, so the only bytes that change
are the 42 bytes of the value itself; the fixture is otherwise byte-identical
to the pinned source.

Usage::

    python tools/plant_fixture.py            # write tests/planted/…
    python tools/plant_fixture.py --check    # recompute and compare (exit 1
                                             # on drift, 2 when the pinned
                                             # source corpus is not fetched)

Everything the derived fixture is built from - source repo, commit, licence,
the rule it must match, and the expected finding - is recorded in
``tests/planted/manifest.json``, which ``tests/integration/test_m2_exit.py``
asserts against.  The fixture lives under ``tests/planted/`` (not
``tests/fixtures/``) because that tree is fully regenerated by
``tools/extract_examples.py`` and is counted by
``tests/contract/test_fixture_corpora.py``.

Licence: the source sample is Apache-2.0 (omerbenamram/evtx), pinned at the
commit recorded in ``tests/planted/manifest.json``; the derived fixture is
distributed under the same licence.
"""
from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Pinned evtx-rs sample (``tools/corpus_fetch.py`` fetches and verifies it).
SOURCE_REL = Path(".corpus") / "evtx-rs" / "sysmon.evtx"
OUTPUT_REL = Path("tests") / "planted" / "sysmon_planted.evtx"

RECORD_ID = 1742
FIELD = "CommandLine"
OLD_VALUE = "ping  -n 6 127.0.0.1 "
NEW_VALUE = "ping.exe whoami /priv"

CHUNK_SIZE = 65536
HEADER_SIZE = 4096
CHUNK_HEADER = 0x200


def _records(chunk: bytes):
    """Yield ``(record_id, offset, size)`` for every record in a chunk."""
    off = CHUNK_HEADER
    while off + 24 <= CHUNK_SIZE:
        _marker, size = struct.unpack_from("<II", chunk, off)
        if size == 0 or size > CHUNK_SIZE or off + size > CHUNK_SIZE:
            break
        record_id = struct.unpack_from("<Q", chunk, off + 8)[0]
        yield record_id, off, size
        off += size


def plant(source: bytes) -> bytes:
    if len(OLD_VALUE) != len(NEW_VALUE):
        raise ValueError("plant must be an equal-length replacement")
    data = bytearray(source)
    for index in range((len(data) - HEADER_SIZE) // CHUNK_SIZE):
        base = HEADER_SIZE + index * CHUNK_SIZE
        chunk = bytes(data[base: base + CHUNK_SIZE])
        if chunk[:8] != b"ElfChnk\x00":
            continue
        for record_id, off, size in _records(chunk):
            if record_id != RECORD_ID:
                continue
            needle = OLD_VALUE.encode("utf-16-le")
            start = chunk.find(needle, off, off + size)
            if start < 0:
                raise ValueError(f"record {RECORD_ID}: value not found")
            if chunk.find(needle, start + 1, off + size) >= 0:
                raise ValueError(f"record {RECORD_ID}: value is not unique")
            data[base + start: base + start + len(needle)] = NEW_VALUE.encode("utf-16-le")
            # Keep the file header + the chunk the record lives in: the sample
            # ships truncated tail chunks that the parser rejects.
            return bytes(data[: HEADER_SIZE + CHUNK_SIZE])
    raise ValueError(f"record {RECORD_ID} not found")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / SOURCE_REL)
    parser.add_argument("--output", type=Path, default=ROOT / OUTPUT_REL)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    if not args.source.is_file():
        print(
            f"source corpus not fetched: {args.source}\n"
            "run: python tools/corpus_fetch.py",
            file=sys.stderr,
        )
        return 2

    derived = plant(args.source.read_bytes())
    digest = hashlib.sha256(derived).hexdigest()

    if args.check:
        if not args.output.is_file():
            print(f"missing planted fixture: {args.output}", file=sys.stderr)
            return 1
        committed = args.output.read_bytes()
        if committed != derived:
            print(
                f"planted fixture drifted: committed sha256 "
                f"{hashlib.sha256(committed).hexdigest()} != derived {digest}",
                file=sys.stderr,
            )
            return 1
        print(f"ok {args.output.relative_to(ROOT)} sha256 {digest}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(derived)
    print(f"wrote {args.output} ({len(derived)} bytes) sha256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
